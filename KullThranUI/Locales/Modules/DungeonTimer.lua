local function Apply(target, locale)
    if type(target) ~= "table" then return end
    local translated = values[locale]
    for index, key in ipairs(keys) do target[key] = translated and translated[index] or key end
    for key, byLocale in pairs(tracker) do target[key] = byLocale[locale] or key end
    for label, byLocale in pairs(wings) do target["Dungeon wing: " .. label] = byLocale[locale] or label end
    for key, byLocale in pairs(shared) do
        if target[key] == nil or target[key] == key then target[key] = byLocale[locale] or target[key] or key end
    end
end

for _, locale in ipairs({ "enUS", "esES", "deDE", "frFR", "itIT", "ptBR", "ruRU", "koKR", "zhCN", "zhTW" }) do
    Apply(locales[locale], locale)
end
if locales.esMX and locales.esMX ~= locales.esES then Apply(locales.esMX, "esES") end
if locales.ptPT and locales.ptPT ~= locales.ptBR then Apply(locales.ptPT, "ptBR") end
